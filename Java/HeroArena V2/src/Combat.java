import java.util.List;

public abstract class Combat {
    protected List<Hero> heroList; //extended Klassen dürfen von protected erben

    public Combat(List<Hero> heroList) {
        this.heroList = heroList;
    }

    public abstract String gameMode(); //Name der Game Mode

    public abstract void runCombat(); //Ablauf des Schlagaustausches

    public abstract Hero determineWinner(); //Ermittlung des Gewinners

    public void play() { //Methode für Main mit Ausgabe des Gewinners

        System.out.println("~ " + gameMode() + " ~");

        runCombat();

        Hero winner = determineWinner();

        System.out.println(
                winner.getHeroName() + " wins the " + gameMode() + "!"
        );
    }
}

